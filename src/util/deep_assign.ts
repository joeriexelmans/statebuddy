
const isPlainObject = (obj: any) => obj && typeof obj === "object" && !Array.isArray(obj)
  // @ts-ignore
  && obj.__proto__ === ({}).__proto__;
// is this an object with only numbers as keys?
const isArrayLikeObject = (obj: any) => {
  const keys = Object.keys(obj);
  if (keys.length === 0) return false;
  return keys.every(key => /^-?\d+$/.test(key));
};
const arrayLikeObjToArray = (obj: any) => {
  const result = [];
  for (let i = 0; true; i++) {
    if (!Object.hasOwn(obj, i)) break;
    result.push(obj[i]);
  }
  return result;
};
// Similar to Object.assign, but deep (recursive).
// Pure function (does not modify 'target' or 'source').
// 'path' argument is only for debugging.

export function myPureDeepAssign(target: any, source: any, path: string[] = []): any {
  if (isPlainObject(source) && isArrayLikeObject(source)) {
    // workaround for a previous iteration of the deep assign function (generated by ChatGPT) which contained a flaw where it would sometimes convert arrays to objects.
    // so a bunch of my models are fucked up and this fixes it.
    source = arrayLikeObjToArray(source);
  }
  if (Array.isArray(target)) {
    if (Array.isArray(source)) {
      // console.log('could merge arrays', path.join('.'), target, source);
      return source;

      // // types are compatible -> merge element-wise
      // const minLength = Math.min(target.length, source.length);
      // const merged = Array(minLength);
      // for (let i=0; i<minLength; i++) {
      //   merged[i] = myPureDeepAssign(target[i], source[i]);
      // }
      // return [...merged, ...target.slice(minLength), ...source.slice(minLength).map(srcEl => myPureDeepAssign(undefined, srcEl))];
    }
  }
  else {
    if (isPlainObject(target)) {
      if (isPlainObject(source)) {
        // types are compatible -> merge element-wise
        const merged = Object.assign({}, target); // shallow copy target
        for (const [srcKey, srcVal] of Object.entries(source)) {
          merged[srcKey] = myPureDeepAssign(target[srcKey], myPureDeepAssign(undefined, srcVal), [...path, srcKey]);
        }
        return merged;
      }
    }
  }

  // catch-all (incompatible types, ...): source obliterates target
  return source;
}
